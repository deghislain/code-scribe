def _translate_labels(labels: dict[str, str], language: str) -> dict[str, str]:
    """
    Return a copy of *labels* with all values translated into *language*.

    For English (or when the LLM call fails) the original dict is returned
    unchanged.  A single LLM call translates all strings in one shot to
    minimise latency and rate-limit usage.

    Technical terms, code identifiers, file names, and proper nouns that
    have no standard translation are intentionally left in English.
    """
    if language.lower() in _UNTRANSLATED:
        return labels

    # Build a numbered list so the LLM can return lines we can parse reliably
    entries = list(labels.items())
    numbered = "\n".join(f"{i+1}. {v}" for i, (_, v) in enumerate(entries))

    prompt = (
        f"Translate the following UI strings into {language}. "
        "Rules:\n"
        "- Return ONLY the translated lines, one per line, in the same numbered order.\n"
        "- Keep the number prefix (e.g. '1. ').\n"
        "- Leave technical terms, code identifiers, file/path names, command-line strings, "
        "brand names (e.g. Code-Scribe), and proper nouns that lack a standard translation "
        "in their original English form.\n"
        "- Do NOT add explanations, blank lines between items, or any other text.\n\n"
        f"Strings to translate:\n{numbered}"
    )

    try:
        raw = llm.ask(prompt, max_tokens=1024)
        lines = [ln.strip() for ln in raw.strip().splitlines() if ln.strip()]
        if len(lines) < len(entries):
            log.warning(
                "Label translation returned %d lines for %d entries — "
                "falling back to English for missing entries",
                len(lines), len(entries),
            )
        # Strip the "N. " prefix and rebuild the dict
        translated: dict[str, str] = {}
        for i, (key, original) in enumerate(entries):
            if i < len(lines):
                # Remove leading "1. " / "12. " prefix if present
                line = lines[i]
                dot_pos = line.find(". ")
                if dot_pos != -1 and line[:dot_pos].isdigit():
                    line = line[dot_pos + 2:]
                translated[key] = line or original
            else:
                translated[key] = original
        return translated
    except Exception as exc:
        log.warning("Label translation failed (%s) — falling back to English", exc)
        return labels


