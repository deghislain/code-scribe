# User Guide
# ---------------------------------------------------------------------------

def generate_user_guide(
    job_id: int,
    stack_profile: dict,
    ui_map: dict,
    checkpoints: list[dict],
    repo_dir: str,
    language: str = "English",
) -> tuple[str, str, str, str]:
    """
    Generate the End User Guide as a complete HTML string.
    Returns ``(html, doc_title, generated_by_label, version_label)`` — all
    strings are already translated into *language*.
    """
    root = Path(repo_dir)
    readme = _read_safe(root / "README.md") or _read_safe(root / "README.rst")
    tree = _tree_listing(root)
    frameworks = ", ".join(stack_profile.get("frameworks", ["unknown"]))
    lang_labels = ", ".join(stack_profile.get("languages", ["unknown"]))
    routes_text = "\n".join(
        f"  {r['path']}: {r.get('description', '')}"
        for r in ui_map.get("routes", [])
    )
    test_checkpoint = next(
        (c for c in checkpoints if c["checkpoint_name"] == "tests_run"), {}
    )
    test_evidence = json.dumps(test_checkpoint.get("evidence", {}), indent=2)[:1000]

    # Translate all static UI strings in a single LLM call
    log.info("Translating User Guide labels into %s", language)
    t = _translate_labels(_USER_GUIDE_LABELS, language)

    ui_section_body = (
        f"<p>[UNVERIFIED] {t['section_no_gui']}</p>"
        if not ui_map.get("routes")
        else None  # will be filled by LLM call below
    )

    # Build task list for all LLM sections.
    # Each tuple: (section_index, title, evidence, instruction, max_tokens)
    # Section indices match their final insertion order (0-based within LLM sections).
    tasks: list[tuple] = [
        (0, t["section_sys_req"],
         f"Stack: {frameworks}\nLanguages: {lang_labels}\n\nREADME:\n{readme}",
         "List minimum OS, runtime versions, and browser requirements for an end user.",
         1024),
        (1, t["section_install"],
         f"README:\n{readme}\n\nDirectory tree:\n{tree}",
         "Provide step-by-step installation instructions for an end user. Focus on what "
         "a non-developer needs to do to get the application running.",
         1024),
        (2, t["section_getting_started"],
         f"README:\n{readme}\nRoutes:\n{routes_text}",
         "Describe how to launch the application and reach the main entry point.",
         1024),
        (4, t["section_features"],
         f"README:\n{readme}\nRoutes:\n{routes_text}",
         "List and describe the main features available to end users.",
         1024),
        (5, t["section_config"],
         f"README:\n{readme}\nDirectory tree:\n{tree}",
         "Describe any end-user-facing configuration options (settings files, environment variables visible to users, etc.).",
         1024),
        (6, t["section_tasks"],
         f"README:\n{readme}\nRoutes:\n{routes_text}",
         "Describe 3–5 common tasks an end user would perform. Use numbered steps.",
         1024),
        (7, t["section_trouble"],
         f"README:\n{readme}\nTest output:\n{test_evidence}",
         "List common user-facing problems and their solutions.",
         1024),
        (8, t["section_faq"],
         f"README:\n{readme}\nRoutes:\n{routes_text}",
         "Write 4–6 FAQ entries in a Q&A format relevant to end users.",
         1024),
        (9, t["section_glossary"],
         f"Stack: {frameworks} / {lang_labels}\nREADME:\n{readme}",
         "Define 5–8 technical terms an end user may encounter.",
         1024),
        (10, t["section_support"],
         f"README:\n{readme}",
         "Describe how end users can get help or report issues.",
         512),
        (11, t["section_appendices"],
         f"Stack: {frameworks}\nRoutes:\n{routes_text}",
         "Include any keyboard shortcuts, accessibility notes, or additional reference material.",
         512),
    ]

    # Add UI overview section to the batch if there are routes
    if ui_map.get("routes"):
        tasks.append((3, t["section_ui_overview"],
                       f"Routes and pages:\n{routes_text}",
                       "Describe each major page/view in plain language. What does the user see and do there?",
                       2048))

    log.info("Generating End User Guide for job %d (%d sections)", job_id, len(tasks) + 1)
    llm_results = _run_sections_sequential(tasks, language=language)

    # Assemble sections in order
    sections_html = ""

    # Static overview section (translated)
    sections_html += _section(
        t["section_overview"],
        f"<p>{t['overview_intro']} {t['overview_stack_label']}: "
        f"<strong>{frameworks}</strong> ({lang_labels}).</p>"
        f"<p>{readme[:800]}</p>",
    )

    sections_html += _section(t["section_sys_req"],         llm_results[0])
    sections_html += _section(t["section_install"],          llm_results[1])
    sections_html += _section(t["section_getting_started"],  llm_results[2])
    sections_html += _section(
        t["section_ui_overview"],
        llm_results.get(3, ui_section_body),
    )
    sections_html += _section(t["section_features"],         llm_results[4])
    sections_html += _section(t["section_config"],           llm_results[5])
    sections_html += _section(t["section_tasks"],            llm_results[6])
    sections_html += _section(t["section_trouble"],          llm_results[7])
    sections_html += _section(t["section_faq"],              llm_results[8])
    sections_html += _section(t["section_glossary"],         llm_results[9])
    sections_html += _section(t["section_support"],          llm_results[10])
    sections_html += _section(t["section_appendices"],       llm_results[11])

    return sections_html, t["doc_title"], t["generated_by"], t["version_label"]


